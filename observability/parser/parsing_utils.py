def parse_tap_output(output: str) -> dict[str, str] | None:
    """Parse TAP (Test Anything Protocol) output.

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If no TAP output found
    """
    results = {}

    clean = re.sub(r"\x1b\[[0-9;]*m", "", output)

    has_tap_version = "TAP version" in clean
    has_ok_not_ok = re.search(r"^(?:ok|not ok)\s+\d+", clean, re.MULTILINE)
    has_test_plan = re.search(r"^\d+\.\.\d+$", clean, re.MULTILINE)
    has_tap_summary = re.search(r"^#\s*(?:tests|pass|fail)\s+\d+", clean, re.MULTILINE)

    if not (has_tap_version or has_ok_not_ok or has_test_plan or has_tap_summary):
        return None

    tap_pattern = re.compile(
        r"^(ok|not ok)\s+(\d+)\s*(?:-\s*)?(.+?)?\s*(?:#\s*(SKIP|TODO).*)?$",
        re.MULTILINE | re.IGNORECASE,
    )

    for match in tap_pattern.finditer(clean):
        status = match.group(1).lower()
        test_num = match.group(2)
        test_name = match.group(3).strip() if match.group(3) else f"test_{test_num}"
        directive = match.group(4).upper() if match.group(4) else None

        test_name = re.sub(r"\s*#\s*time=[\d.]+\s*m?s?\s*$", "", test_name).strip()

        if not test_name:
            test_name = f"test_{test_num}"

        if directive == "SKIP":
            results[test_name] = "SKIPPED"
        elif directive == "TODO":
            results[test_name] = "PASSED" if status == "ok" else "SKIPPED"
        else:
            results[test_name] = "PASSED" if status == "ok" else "FAILED"

    return results if results else None


def parse_mocha_console(output: str) -> dict[str, str] | None:
    """Parse Mocha console output with checkmarks.

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If no Mocha console output found
    """
    results = {}

    clean = re.sub(r"\x1b\[[0-9;]*m", "", output)

    for line in clean.split("\n"):
        stripped = line.strip()
        if not stripped:
            continue

        pass_match = re.match(r"^\s*[✔✓]\s+(.+?)(?:\s+\(\d+\s*m?s\))?\s*$", line)
        if pass_match:
            test_name = pass_match.group(1).strip()
            results[test_name] = "PASSED"
            continue

        fail_match = re.match(r"^\s*\d+\)\s+(.+?)\s*$", line)
        if fail_match:
            test_name = fail_match.group(1).strip()
            results[test_name] = "FAILED"
            continue

        skip_match = re.match(r"^\s*-\s+(.+?)\s*$", line)
        if skip_match:
            test_name = skip_match.group(1).strip()
            results[test_name] = "SKIPPED"
            continue

    if results:
        return results

    passing = 0
    failing = 0
    pending = 0

    pass_match = re.search(r"(\d+)\s+passing(?:\s+\([^)]+\))?", clean)
    if pass_match:
        passing = int(pass_match.group(1))

    fail_match = re.search(r"(\d+)\s+failing", clean)
    if fail_match:
        failing = int(fail_match.group(1))

    pend_match = re.search(r"(\d+)\s+pending", clean)
    if pend_match:
        pending = int(pend_match.group(1))

    if passing > 0 or failing > 0:
        for i in range(passing):
            results[f"test_{i+1}"] = "PASSED"
        for i in range(failing):
            results[f"failing_test_{i+1}"] = "FAILED"
        for i in range(pending):
            results[f"pending_test_{i+1}"] = "SKIPPED"

    return results if results else None


def parse_swift_testing(output: str) -> dict[str, str] | None:
    """Parse Swift Testing framework output (Swift 6+).

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If no Swift Testing output found
    """
    results = {}

    clean = re.sub(r"\x1b\[[0-9;]*m", "", output)

    test_pattern = re.compile(
        r'^\s*([✔✓✘✗◇])\s+Test\s+"([^"]+)"\s+(passed|failed|skipped)',
        re.MULTILINE | re.IGNORECASE,
    )

    for match in test_pattern.finditer(clean):
        test_name = match.group(2)
        status = match.group(3).lower()

        if status == "passed":
            results[test_name] = "PASSED"
        elif status == "failed":
            results[test_name] = "FAILED"
        else:
            results[test_name] = "SKIPPED"

    if not results:
        summary_match = re.search(
            r"Test run with (\d+) tests? (passed|failed)", clean
        )
        if summary_match:
            results["test_run"] = (
                "PASSED" if summary_match.group(2) == "passed" else "FAILED"
            )

    return results if results else None


def parse_test_output(output: str, framework: str, validation_code: str | None = None) -> dict[str, str]:
    """
    Parse test output to extract individual test results.

    Args:
        output: Raw test output (stdout/stderr or file contents)
        framework: Test framework name (pytest, vitest, jest, go, junit, mocha, bespoke, etc.)
        validation_code: Optional validation code snippet for bespoke frameworks

    Returns: {'test_id': 'PASSED'|'FAILED'|'SKIPPED'}
    """
    # First, check if output is in the compact pre-processed format
    # This format is generated by the in-container parser (shared/parse_test_output.py)
    compact_results = parse_compact_format(output)
    if compact_results:
        return compact_results
    
    # Handle RAW_OUTPUT prefix from container parser
    # When the container parser couldn't parse, it prefixes with "RAW_OUTPUT\n"
    # Strip this prefix so we can try host-side parsing on the actual content
    if output.startswith("RAW_OUTPUT\n"):
        output = output[len("RAW_OUTPUT\n"):]
    
    # Extract result file content if present (added by run_with_patches)
    if "=== RESULT FILE:" in output:
        # Extract just the content after the header line
        lines = output.split("\n")
        content_lines = []
        in_result_file = False
        for line in lines:
            if line.startswith("=== RESULT FILE:"):
                in_result_file = True
                continue
            if in_result_file:
                content_lines.append(line)
        if content_lines:
            output = "\n".join(content_lines)
    
    # Handle bespoke frameworks specially (may need validation_code)
    if framework in ("bespoke", "bespoke_libgeos"):
        result = parse_bespoke_output(output, validation_code)
        return result or {}

    parsers = {
        "pytest": parse_junit_xml,
        "unittest": parse_junit_xml,
        "junit": parse_junit_xml,
        "maven": parse_maven_text_output,
        "gtest": parse_gtest_json,
        "cargo-nextest": parse_cargo_nextest,
        "go": parse_go_json,
        "jest": parse_jest_vitest_json,
        "vitest": parse_jest_vitest_json,
        "mocha": parse_mocha_json,
        "bun": parse_bun_text,
        "ctest": parse_junit_xml,
        "cppunit": parse_cppunit_text,
        "xctest": parse_xctest_output,
        "testing": parse_swift_testing,
        "busted": parse_junit_xml,
        "luaunit": parse_junit_xml,
        "telescope": parse_telescope_text,
        "lust": parse_lust_text,
        "minitest": parse_minitest_text,
        "make": parse_make_text,
        "cmake": parse_make_text,
        "unity": parse_unity_text,
        "tape": parse_tap_output,
        "tap": parse_tap_output,
        "hardhat": parse_mocha_json,
    }

    parser = parsers.get(framework)
    if parser:
        result = parser(output)
        if not result and framework in ["junit", "maven"]:
            result = parse_maven_text_output(output)
        if not result and framework in ["pytest", "unittest"]:
            result = parse_pytest_console(output)
        if not result and framework in ["jest", "vitest"]:
            result = parse_jest_vitest_console(output)
        if not result and framework in ["jest", "vitest"]:
            result = parse_tap_output(output)
        if not result and framework == "vitest":
            result = parse_mocha_json(output)
        if not result and framework in ["mocha", "hardhat"]:
            result = parse_mocha_console(output)
        if not result and framework in ["jest", "vitest", "mocha", "hardhat"]:
            result = parse_mocha_console(output)
        if not result and framework in ["ctest", "gtest"]:
            result = parse_gtest_console(output)
        if not result and framework in ["ctest", "gtest"]:
            result = parse_make_text(output)
        if not result and framework == "xctest":
            result = parse_swift_testing(output)
        if not result and framework == "xctest":
            result = parse_mocha_console(output)
        if not result and framework in ["tape", "tap"]:
            result = parse_tap_output(output)
        return result or {}

    # Unknown framework - warn and try universal fallbacks
    logger.warning(
        f"Unknown test framework '{framework}', using generic fallback parsers. "
        "Consider adding explicit support for better accuracy."
    )
    result = parse_tap_output(output)
    if result:
        return result

    result = parse_unity_text(output)
    if result:
        return result

    result = parse_swift_testing(output)
    if result:
        return result

    result = parse_mocha_console(output)
    if result:
        return result

    result = parse_make_text(output)
    if result:
        return result

    return {}
