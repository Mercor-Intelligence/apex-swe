def parse_telescope_text(text_output: str) -> dict[str, str] | None:
    """Parse telescope test framework output.

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If telescope failed to run (not the same as tests failing)
    """
    results = {}

    for line in text_output.split("\n"):
        line = line.strip()

        if "✓" in line:
            test_name = line.split("✓", 1)[1].strip()
            if test_name:
                results[test_name] = "PASSED"
        elif line.lower().startswith("success:"):
            test_name = line.split(":", 1)[1].strip()
            if test_name:
                results[test_name] = "PASSED"

        elif "✗" in line:
            test_name = line.split("✗", 1)[1].strip()
            if test_name:
                results[test_name] = "FAILED"
        elif line.lower().startswith("failed:"):
            test_name = line.split(":", 1)[1].strip()
            if test_name:
                results[test_name] = "FAILED"

        elif line.startswith("- ") and "skip" in line.lower():
            test_name = line[2:].strip()
            test_name = re.sub(
                r"\s*\(skipped\)\s*$", "", test_name, flags=re.IGNORECASE
            )
            if test_name:
                results[test_name] = "SKIPPED"
        elif line.lower().startswith("skipped:"):
            test_name = line.split(":", 1)[1].strip()
            if test_name:
                results[test_name] = "SKIPPED"

    if not results:
        summary_pattern = r"(\d+)\s+passed.*?(\d+)\s+failed"
        match = re.search(summary_pattern, text_output.lower())
        if match:
            passed = int(match.group(1))
            failed = int(match.group(2))

            for i in range(passed):
                results[f"test_{i+1}"] = "PASSED"
            for i in range(failed):
                results[f"test_failed_{i+1}"] = "FAILED"

    if not results:
        error_indicators = [
            "Error:",
            "error loading module",
            "attempt to call",
            "bad argument",
            "stack traceback:",
        ]
        has_errors = any(indicator in text_output for indicator in error_indicators)
        return None if has_errors else results

    return results


def parse_lust_text(text_output: str) -> dict[str, str]:
    """Parse lust test framework output."""
    results = {}

    test_pattern = re.compile(r"^\s*(.+?)\s+\.\.\.\s+(ok|FAILED|ERROR)", re.MULTILINE)
    matches = test_pattern.findall(text_output)

    if matches:
        for test_name, status in matches:
            test_name = test_name.strip()
            if status == "ok":
                results[test_name] = "PASSED"
            else:
                results[test_name] = "FAILED"
        return results

    failure_pattern = re.compile(r"^([^\s:]+\.lua):(\d+):\s*(.+)$", re.MULTILINE)
    failures = failure_pattern.findall(text_output)

    if failures:
        for filepath, _, description in failures:
            test_id = f"{filepath}::{description.strip()}"
            results[test_id] = "FAILED"

    summary_match = re.search(
        r"(\d+)\s+tests?,\s+(\d+)\s+failures?", text_output.lower()
    )
    if summary_match:
        total_tests = int(summary_match.group(1))
        failures = int(summary_match.group(2))

        if not results:
            passed = total_tests - failures
            for i in range(passed):
                results[f"test_{i+1}"] = "PASSED"
            for i in range(failures):
                results[f"test_failed_{i+1}"] = "FAILED"
            return results

    if not results:
        if "0 failures" in text_output.lower() or "0 errors" in text_output.lower():
            results["test_suite"] = "PASSED"
        else:
            results["test_suite"] = "FAILED"

    return results


def parse_bespoke_output(output: str, validation_code: str | None = None) -> dict[str, str] | None:
    """Parse bespoke/custom test output using validation_code_snippet.
    
    Bespoke tests have a custom validation snippet that evaluates the output.
    If no validation code is provided, falls back to generic success/failure detection.
    
    Args:
        output: Raw test output
        validation_code: Python code snippet that sets result dict (optional)
    
    Returns:
        dict mapping test_id to status, or None if framework failed to run
    """
    results = {}
    
    if validation_code:
        # Execute the validation code snippet
        # The snippet should set result = {"test_name": "PASSED"/"FAILED"}
        try:
            local_vars: dict = {"output": output, "result": {}}
            exec(validation_code, {}, local_vars)
            raw_result = local_vars.get("result", {})
            
            # Normalize the results
            for test_id, status in raw_result.items():
                if isinstance(status, str):
                    status_upper = status.upper()
                    if status_upper in ("PASSED", "PASS", "OK", "SUCCESS"):
                        results[test_id] = "PASSED"
                    elif status_upper in ("FAILED", "FAIL", "ERROR", "FAILURE"):
                        results[test_id] = "FAILED"
                    elif status_upper in ("SKIPPED", "SKIP", "PENDING"):
                        results[test_id] = "SKIPPED"
            
            if results:
                return results
        except Exception:
            pass
    
    # Fallback: generic success/failure detection
    return parse_bespoke_libgeos(output)


def parse_bespoke_libgeos(text_output: str) -> dict[str, str] | None:
    """Parse libgeos/GEOS test output format.

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If libgeos tests failed to run (not the same as tests failing)
    """
    results = {}

    # Parse individual test group lines: "TestSuite::TestName: ...."
    test_line_pattern = re.compile(
        r"^([a-zA-Z_][a-zA-Z0-9_:]*::[a-zA-Z_][a-zA-Z0-9_]*)\s*:\s*(.+?)(?:\n|$)",
        re.MULTILINE,
    )

    for match in test_line_pattern.finditer(text_output):
        test_id = match.group(1)
        test_output_line = match.group(2)
        has_failure = bool(
            re.search(r"\[.*=[FX]\]|(?<!\w)[FX](?!\w)", test_output_line)
        )
        results[test_id] = "FAILED" if has_failure else "PASSED"

    if results:
        # If the suite completed successfully, keep individual results as-is.
        # If the suite timed out or crashed (no summary), the run is incomplete —
        # mark everything FAILED so new tests added by the golden patch show as F2P.
        if "tests summary: ok:" not in text_output:
            results = {k: "FAILED" for k in results}
        return results

    # No individual test lines found — fall back to synthetic "yes" marker
    if "tests summary: ok:" in text_output:
        return {"yes": "PASSED"}
    if "tests summary:" in text_output and "ok:" not in text_output:
        return {"yes": "FAILED"}

    error_indicators = [
        "error:",
        "undefined reference",
        "fatal error:",
        "ld returned",
        "cannot find -l",
    ]
    has_errors = any(indicator in text_output for indicator in error_indicators)
    return None if has_errors else results


def _normalize_swift_test_name(raw_name: str) -> str:
    """Normalize XCTest case identifiers from swift test console output."""
    name = raw_name.strip()

    if name.startswith("-[") and name.endswith("]"):
        inner = name[2:-1].strip()
        if " " in inner:
            class_name, method = inner.split(" ", 1)
            return f"{class_name}::{method}"
        return inner

    if "." in name:
        parts = name.split(".", 1)
        return f"{parts[0]}::{parts[1]}"

    return name


def parse_swift_test_text(text_output: str) -> dict[str, str]:
    """Parse vanilla `swift test` console output (without --xunit-output)."""
    results = {}
    test_case_pattern = re.compile(
        r"Test Case '([^']+)' (passed|failed|skipped)", re.IGNORECASE
    )

    for match in test_case_pattern.finditer(text_output):
        raw_name, status = match.groups()
        test_id = _normalize_swift_test_name(raw_name)
        results[test_id] = status.upper()

    if results:
        return results

    summary_match = re.search(
        r"Executed\s+(\d+)\s+tests?,\s+with\s+(\d+)\s+failures?",
        text_output,
        re.IGNORECASE,
    )
    if summary_match:
        total_tests = int(summary_match.group(1))
        failures = int(summary_match.group(2))
        passes = max(total_tests - failures, 0)

        for i in range(passes):
            results[f"swift_test_pass_{i+1}"] = "PASSED"
        for i in range(failures):
            results[f"swift_test_fail_{i+1}"] = "FAILED"

    return results


