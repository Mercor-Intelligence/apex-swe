def normalize_test_id(test_id: str, framework: str) -> str:
    """Normalize test IDs by removing unstable runtime prefixes and standardizing formats.

    Args:
        test_id: Original test ID from parser
        framework: Test framework name (for framework-specific normalization rules)

    Returns:
        Normalized test ID with unstable prefixes removed and format standardized
    """
    # Universal pattern: Remove (N/M) or [N/M] prefixes (test execution order)
    normalized = re.sub(r"^[\(\[]?\s*\d+/\d+[\)\]]?\s+", "", test_id)

    # Universal pattern: Remove #N prefix (test numbering)
    normalized = re.sub(r"^#\s*\d+\s+", "", normalized)

    # Universal pattern: Remove "N. " prefix (numbered list)
    normalized = re.sub(r"^\d+\.\s+", "", normalized)

    # GTest/CTest normalization: standardize . vs :: separator
    # GTest uses formats like:
    #   - TestClass::TestName (standard with :: separator)
    #   - TestClass.TestName (sometimes uses . separator)
    #   - InstantiationName/TestClass.TestName/ParamIndex (parameterized tests)
    # We standardize to :: separator between class and test name
    if framework in ("gtest", "ctest"):
        # Handle parameterized test format: InstantiationName/TestClass.TestName/ParamIndex
        param_match = re.match(r"^([^/]+)/([^.]+)\.([^/]+)(?:/(.+))?$", normalized)
        if param_match:
            instantiation, classname, testname, param = param_match.groups()
            if param:
                normalized = f"{instantiation}/{classname}::{testname}/{param}"
            else:
                normalized = f"{instantiation}/{classname}::{testname}"
        # Handle simple format: TestClass.TestName -> TestClass::TestName
        elif "::" not in normalized and "." in normalized:
            # Only convert if it looks like ClassName.TestName (both parts are identifiers)
            parts = normalized.split(".", 1)
            if len(parts) == 2 and parts[0] and parts[1]:
                # Check both parts look like identifiers (start with letter/underscore)
                if re.match(r"^[A-Za-z_]", parts[0]) and re.match(r"^[A-Za-z_]", parts[1]):
                    normalized = f"{parts[0]}::{parts[1]}"

    # Pytest-specific normalization: convert path format to module format
    # e.g., "repo/tests/unit/test_foo.py::TestClass::test_method"
    #    -> "tests.unit.test_foo.TestClass::test_method"
    if framework in ("pytest", "python"):
        if "::" in normalized:
            parts = normalized.split("::")
            file_part = parts[0]
            # Remove common prefixes like "repo/", "src/", etc.
            file_part = re.sub(r"^(?:repo|src|source|lib|app)/", "", file_part)
            # Remove .py extension
            file_part = re.sub(r"\.py$", "", file_part)
            # Convert slashes to dots (path to module)
            file_part = file_part.replace("/", ".")
            
            # Reconstruct: module.class::method (standard pytest nodeid format)
            # If we have module::class::method, convert to module.class::method
            if len(parts) == 3:
                # file_part::class::method -> file_part.class::method
                normalized = f"{file_part}.{parts[1]}::{parts[2]}"
            elif len(parts) == 2:
                # file_part::method -> file_part::method (keep as is)
                normalized = f"{file_part}::{parts[1]}"
            else:
                # More parts, just join with ::
                normalized = "::".join([file_part] + parts[1:])
        else:
            # Handle case where it's just a file path without ::
            normalized = re.sub(r"^(?:repo|src|source|lib|app)/", "", normalized)
            normalized = re.sub(r"\.py$", "", normalized)
            normalized = normalized.replace("/", ".")

    return normalized


def parse_jest_vitest_console(output: str) -> dict[str, str] | None:
    """Parse Jest/Vitest console output (when JSON output is not available).

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
    """
    ansi_pattern = re.compile(r"\x1b\[[0-9;]*m")
    output = ansi_pattern.sub("", output)

    results = {}

    suite_pattern = re.compile(
        r"^(PASS|FAIL)\s+(?:\w+\s+)?(\S+\.(?:test|spec)\.[jt]sx?)(?:\s+\([^)]+\))?",
        re.MULTILINE,
    )

    for match in suite_pattern.finditer(output):
        status = match.group(1)
        test_file = match.group(2)
        results[test_file] = "PASSED" if status == "PASS" else "FAILED"

    vitest_file_pattern = re.compile(
        r"^\s*([✓✔]|[✕✗×])\s+(\S+\.(?:test|spec)\.[jt]sx?)\s+\([^)]+\)",
        re.MULTILINE,
    )

    for match in vitest_file_pattern.finditer(output):
        mark = match.group(1)
        test_file = match.group(2)
        if mark in "✓✔":
            results[test_file] = "PASSED"
        else:
            results[test_file] = "FAILED"

    check_pattern = re.compile(
        r"^\s*([✓✔]|[✕✗×])\s+(.+?)(?:\s+\(\d+\s*m?s\))?\s*$",
        re.MULTILINE,
    )

    for match in check_pattern.finditer(output):
        mark = match.group(1)
        test_name = match.group(2).strip()
        if (
            test_name.endswith((".ts", ".tsx", ".js", ".jsx"))
            and test_name in results
        ):
            continue
        if mark in "✓✔":
            results[test_name] = "PASSED"
        else:
            results[test_name] = "FAILED"

    return results if results else None


def parse_pytest_console(output: str) -> dict[str, str] | None:
    """Parse pytest console output (verbose mode with PASSED/FAILED markers).

    Handles two formats:
    1. Verbose mode: "test_file.py::TestClass::test_name PASSED"
    2. Short test summary: "FAILED test_file.py::TestClass::test_name"

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
    """
    results = {}

    # Pattern 1: Verbose mode - "test_id STATUS"
    verbose_pattern = re.compile(
        r'^([\w/\-\.]+(?:::[\w\-\[\]\(\),\s<>=\'\\"]+)+)\s+'
        r"(PASSED|FAILED|SKIPPED|ERROR|XFAIL|XPASS)",
        re.MULTILINE,
    )

    for match in verbose_pattern.finditer(output):
        test_id = match.group(1).strip()
        status = match.group(2)

        if status in ("PASSED", "XPASS"):
            results[test_id] = "PASSED"
        elif status in ("FAILED", "ERROR", "XFAIL"):
            results[test_id] = "FAILED"
        elif status == "SKIPPED":
            results[test_id] = "SKIPPED"

    # Pattern 2: Short test summary - "STATUS test_id" (used with parallel pytest / -n flag)
    # This section appears after "=== short test summary info ===" in pytest output
    # Matches: "FAILED path/to/test.py::TestClass::test_method" or with parameterized tests
    summary_pattern = re.compile(
        r"^(PASSED|FAILED|SKIPPED|ERROR|XFAIL|XPASS)\s+"
        r"(\S+\.py::\S+)",
        re.MULTILINE,
    )

    for match in summary_pattern.finditer(output):
        status = match.group(1)
        test_id = match.group(2).strip()

        # Don't overwrite if we already have a result from verbose output
        if test_id in results:
            continue

        if status in ("PASSED", "XPASS"):
            results[test_id] = "PASSED"
        elif status in ("FAILED", "ERROR", "XFAIL"):
            results[test_id] = "FAILED"
        elif status == "SKIPPED":
            results[test_id] = "SKIPPED"

    return results if results else None


def parse_make_text(output: str) -> dict[str, str] | None:
    """Parse make/cmake custom C test output.

    Returns:
        dict[str, str]: Test results mapping test IDs to status (PASSED/FAILED/SKIPPED)
        None: If make tests failed to run (not the same as tests failing)
    """
    results = {}

    clean = re.sub(r"\x1b\[[0-9;]*m", "", output)

    current_test = None
    test_passed = True

    for line in clean.split("\n"):
        test_match = re.match(r"^(test_*\w+):\s*$", line.strip())
        if test_match:
            if current_test:
                results[current_test] = "PASSED" if test_passed else "FAILED"
            current_test = test_match.group(1)
            test_passed = True
            continue

        if "[PASS:" in line or "[PASS]" in line:
            pass
        elif "[FAIL:" in line or "[FAIL]" in line:
            test_passed = False

    if current_test:
        results[current_test] = "PASSED" if test_passed else "FAILED"

    if results:
        return results

    simple_pattern = re.compile(
        r"^(\w+):\s*(PASS|FAIL|OK|FAILED|ERROR)\s*$", re.IGNORECASE | re.MULTILINE
    )
    for match in simple_pattern.finditer(clean):
        test_name = match.group(1)
        status = match.group(2).upper()
        if status in ["PASS", "OK"]:
            results[test_name] = "PASSED"
        else:
            results[test_name] = "FAILED"

    if results:
        return results

    pass_desc_pattern = re.compile(
        r"^\[?(PASS|FAIL)\]?:?\s+(.+?)\s*$", re.IGNORECASE | re.MULTILINE
    )
    for match in pass_desc_pattern.finditer(clean):
        status = match.group(1).upper()
        test_name = match.group(2).strip()
        test_name = re.sub(r"^All\s+", "", test_name)
        if status == "PASS":
            results[test_name] = "PASSED"
        else:
            results[test_name] = "FAILED"

    if results:
        return results

    ctest_fail = re.compile(r"\[\s*FAILED\s*\]\s+(\S+)", re.IGNORECASE)

    for match in ctest_fail.finditer(clean):
        test_name = match.group(1)
        if not test_name.isdigit():
            results[test_name] = "FAILED"

    ctest_individual = re.compile(
        r"(?:\d+/\d+\s+)?Test\s+#?\d+:\s+(\S+)\s+\.+\s*(Passed|Failed|\*\*\*Failed)",
        re.IGNORECASE,
    )
    for match in ctest_individual.finditer(clean):
        test_name = match.group(1)
        status = match.group(2).lower()
        results[test_name] = "PASSED" if "pass" in status else "FAILED"

    return results if results else None


